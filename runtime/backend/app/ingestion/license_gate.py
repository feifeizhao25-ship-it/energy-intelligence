def align(sources: list[dict]) -> list[dict]:
    """把研究名单与闸门登记对齐。数量或名称对不上则整表拒绝启用。"""
    if len(sources) != len(DECISIONS):
        raise ValueError("来源数量与闸门登记不一致：%s != %s" % (len(sources), len(DECISIONS)))
    aligned = []
    for item, spec in zip(sources, DECISIONS):
        name = str(item.get("name") or "")
        if item.get("category") != spec["category"] or spec["token"] not in name:
            aligned.append({
                **spec,
                "enabled": False,
                "code": "mismatch",
                "reason": "来源条目与闸门登记不一致",
                "parser": "",
                "needs_human": False,
            })
            continue
        aligned.append(dict(spec))
    return aligned
