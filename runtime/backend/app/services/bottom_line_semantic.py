def find_semantic_violations(masked_text: str) -> list[str]:
    """masked_text 应已去掉免责声明（bottom_line._mask）。返回词族名列表，按词族去重、保持顺序。"""
    norm = normalize(masked_text)
    if not norm:
        return []
    found: list[str] = []
    for family, patterns in FAMILIES.items():
        for pattern in patterns:
            if re.search(pattern, norm):
                found.append(family)
                break
    return found
