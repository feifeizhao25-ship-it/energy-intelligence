def rows() -> list[dict]:
    items = []
    number = 1
    for category, source_id, must, questions in GROUPS:
        for question in questions:
            items.append({
                "id": "H%03d" % number,
                "category": category,
                "question": question,
                "must_include": must,
                "required_sources": [{"source_id": source_id}],
                "forbidden": ["建议投资", "预测"],
                "as_of": "2026-10-28",
                "split": "heldout",
            })
            number += 1
    return items


def main() -> None:
    target = Path(__file__).resolve().parents[1] / "data" / "eval" / "heldout_v1.jsonl"
    payload = "\n".join(json.dumps(item, ensure_ascii=False) for item in rows()) + "\n"
    target.write_text(payload, encoding="utf-8")
    print(json.dumps({"wrote": str(target), "questions": len(rows())}, ensure_ascii=False))


if __name__ == "__main__":
    main()
